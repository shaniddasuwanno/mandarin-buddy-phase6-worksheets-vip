function codepoint(emoji:string){return Array.from(emoji).filter(c=>c!=='\ufe0f').map(c=>c.codePointAt(0)!.toString(16)).join('-')}
function ImageIcon({emoji,className}:{emoji:string;className:string}){
 const [stage,setStage]=useState(assets[emoji]?0:2);
 const asset=assets[emoji];
 const title=(name:string)=>name.replace(/(^|[ -])([a-z])/g,(_,prefix,ch)=>prefix+ch.toUpperCase());
 const source=stage<2&&asset?ROOT+'/'+encodeURIComponent(asset[0])+'/'+encodeURIComponent(stage===0?title(asset[1]):asset[1])+'.png':'https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/'+codepoint(emoji)+'.svg';
 return stage<3?<img src={source} alt="" aria-hidden="true" className={className+' object-contain'} draggable={false} onError={()=>setStage(n=>n===0&&asset&&title(asset[1])===asset[1]?2:n+1)}/>:<span aria-hidden="true" className={className+' fluent-native-fallback'}>{emoji}</span>;
}
export default function FluentIcon({emoji,className='h-16 w-16'}:{emoji:string;className?:string}){return <ImageIcon key={emoji} emoji={emoji} className={className}/>;}
